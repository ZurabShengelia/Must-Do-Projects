"""Browser checks on the real app (index.html) with Python Playwright. Run from the repo root:
    python3 scripts/check_app.py
Needs: pip install playwright, then: playwright install chromium"""
import json
from playwright.sync_api import sync_playwright
from qa_common import CONTRAST_JS, OUT, ROOT, SEED, serve

srv, URL = serve(8792)
res = []
def rec(ok, n, d=''): res.append(('pass' if ok else 'FAIL', n, d))
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 1440, 'height': 900}, permissions=['clipboard-read', 'clipboard-write'])
    pg = ctx.new_page(); errs = []
    pg.on('console', lambda m: errs.append(m.text) if m.type in ('error', 'warning') else None)
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(URL)
    pg.evaluate("d => localStorage.setItem('notetaker-notes', JSON.stringify({version:1, notes:d}))", SEED)
    pg.reload(); pg.wait_for_timeout(200)
    names = pg.eval_on_selector_all('.row-title', 'els => els.map(e => e.textContent)')
    rec(names[:2] == ['ქართული ანბანი', 'Sample note two'] and len(names) == 5, 'Existing data loads; bookmarked first, newest next', json.dumps(names, ensure_ascii=False))
    rec(pg.eval_on_selector_all('#filters .tab', 'els => els.map(e => e.textContent)') == ['All5','Bookmarked2','General1','Personal1','Work1','Learning1','Ideas1'], 'Index shows All, Bookmarked and five categories only')
    rec(pg.is_visible('#empty-editor') and pg.is_disabled('#pin') and pg.is_disabled('#delete'), 'Nothing open: empty copy shown, Bookmark and Delete disabled')
    raw = (ROOT / 'index.html').read_text()
    rec('Opening your entries.' in raw, 'Loading state is in the served HTML, so it shows until the entries render')
    pg.click('.row >> nth=1')
    imm = pg.evaluate("() => ({title: document.getElementById('title').value, turning: document.getElementById('page').classList.contains('turning')})")
    rec(imm['title'] == 'Sample note two', 'Page turn: the new entry is in place immediately (never delayed by the animation)', json.dumps(imm))
    dur = pg.evaluate("() => { const cs = getComputedStyle(document.getElementById('page')); return [cs.animationName, cs.animationDuration]; }")
    rec(dur[0] == 'turn' and float(dur[1].rstrip('s')) < 0.4, 'Page turn plays and lasts under 400ms', json.dumps(dur))
    pg.wait_for_timeout(120); pg.click('.row >> nth=2'); pg.wait_for_timeout(110)
    pg.wait_for_timeout(450)
    rec(not pg.evaluate("document.getElementById('page').classList.contains('turning')"), 'Page turn has finished and cleaned up within 450ms')
    pg.click('.row >> nth=0'); pg.wait_for_timeout(500)
    rec(pg.input_value('#title') == 'ქართული ანბანი' and pg.is_visible('#page-ribbon'), 'Opening a bookmarked entry fills the page and shows the ribbon')
    rec(pg.inner_text('#amended') == 'Amended 7 Nov 2026', 'Amended date shown', pg.inner_text('#amended'))
    pg.wait_for_timeout(450)
    pg.click('#new-note'); pg.fill('#title', 'Test entry'); pg.fill('#content', 'First line\nსაქართველო')
    rec(pg.get_attribute('#status', 'data-state') == 'unsaved' and pg.inner_text('#status-text') == 'Unsaved changes', 'Typing shows Unsaved changes')
    pg.fill('#title', '  Test   entry  '); pg.fill('#content', 'First line\r\nსაქართველო   \n\n')
    pg.wait_for_timeout(900)
    st = pg.evaluate("() => { const n = JSON.parse(localStorage.getItem('notetaker-notes')).notes; const x = n[n.length-1]; return [x.title, x.content]; }")
    rec(st == ['Test entry', 'First line\nსაქართველო'], 'Postel: stored title is trimmed and text normalised', json.dumps(st, ensure_ascii=False))
    pg.fill('#title', 'Test entry'); pg.fill('#content', 'First line\nსაქართველო'); pg.wait_for_timeout(900)
    rec(pg.get_attribute('#status', 'data-state') == 'saved' and pg.inner_text('#status-text') == 'Saved in this browser', 'Autosave reaches Saved in this browser')
    stored = pg.evaluate("JSON.parse(localStorage.getItem('notetaker-notes')).notes.length")
    rec(stored == 6, 'Entry persisted to LocalStorage', str(stored))
    pg.keyboard.press('Alt+b'); pg.wait_for_timeout(100)
    rec(pg.inner_text('#pin') == 'Bookmarked' and pg.is_visible('#page-ribbon'), 'Alt+B bookmarks the open entry')
    pg.click('#filters .tab >> nth=1'); rec(pg.locator('.row').count() == 3, 'Bookmarked filter lists 3 entries')
    pg.click('#filters .tab >> nth=4'); rec(pg.locator('.row').count() == 1, 'Work filter lists 1 entry')
    pg.click('#filters .tab >> nth=6'); pg.click('#filters .tab >> nth=5')
    pg.click('#filters .tab >> nth=6')
    rec('Nothing filed under Ideas' not in pg.inner_text('#list'), 'Ideas filter shows its entry')
    pg.click('#filters .tab >> nth=0'); pg.fill('#search', 'zzz')
    rec('No entry mentions' in pg.inner_text('#list'), 'Search with no match shows specific empty copy', pg.inner_text('#list')[:80])
    pg.fill('#search', '')
    pg.click('.row >> nth=0'); pg.click('#copy')
    pg.wait_for_timeout(150)
    rec(pg.inner_text('#copy') == 'Copied', 'Copy text shows Copied')
    rec(pg.evaluate('navigator.clipboard.readText()') != '', 'Clipboard received the entry text')
    pg.keyboard.press('Escape'); pg.keyboard.press('?')
    rec(pg.evaluate("document.getElementById('shortcuts').open"), '? opens the shortcut sheet'); pg.keyboard.press('Escape')
    pg.click('#delete'); rec(pg.evaluate("document.getElementById('confirm').open"), 'Delete asks for confirmation')
    pg.click('#confirm button[value=cancel]'); rec(pg.evaluate("JSON.parse(localStorage.getItem('notetaker-notes')).notes.length") == 6, 'Cancel keeps the entry')
    pg.click('#delete'); pg.click('#confirm button[value=ok]'); pg.wait_for_timeout(100)
    rec(pg.evaluate("JSON.parse(localStorage.getItem('notetaker-notes')).notes.length") == 5, 'Confirmed delete removes the entry')
    pg.click('.row >> nth=0'); pg.click('#theme'); pg.reload(); pg.wait_for_timeout(150)
    rec(pg.evaluate("document.documentElement.dataset.theme") == 'dark', 'Dark theme persists after reload')
    pg.click('.row >> nth=0'); pg.wait_for_timeout(100)
    pg.wait_for_timeout(450)
    for theme in ('dark', 'light'):
        pg.evaluate(f"document.documentElement.setAttribute('data-theme','{theme}')"); pg.wait_for_timeout(100)
        items = pg.evaluate(CONTRAST_JS)
        fails = [i for i in items if i['ratio'] < i['need']]
        rec(not fails, f'Computed text contrast meets WCAG AA, {theme} ({len(items)} text elements)', '; '.join(f"{i['text']!r} {i['ratio']:.2f}" for i in fails[:5]))
        muted = pg.evaluate("() => { const d = document.createElement('span'); d.style.color='var(--muted)'; document.body.appendChild(d); const c = getComputedStyle(d).color; d.remove(); return c; }")
        md = [i['text'] for i in items if i['onDesk'] and i['fg'] == muted]
        rec(not md, f'No muted-colored text on the desk, {theme}', json.dumps(md))
    pg.reload(); pg.wait_for_timeout(150)
    pg.keyboard.press('Tab'); rec('skip' in pg.evaluate('document.activeElement.className'), 'First Tab stop is the skip link')
    bad = []; n = 0
    for _ in range(30):
        pg.keyboard.press('Tab'); n += 1
        i = pg.evaluate("() => { const e = document.activeElement, s = getComputedStyle(e); return {t: e.tagName, w: s.outlineWidth, st: s.outlineStyle, id: e.id || e.className}; }")
        if i['t'] == 'BODY': break
        if not (i['w'] == '2px' and i['st'] == 'solid'): bad.append(i)
    rec(not bad, f'Every Tab stop shows the 2px focus ring ({n} stops)', json.dumps(bad[:3]))
    for w, h in ((1440, 900), (1280, 800), (1101, 800), (1024, 768)):
        pg.set_viewport_size({'width': w, 'height': h}); pg.wait_for_timeout(120)
        rec(pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth") <= 0, f'No horizontal overflow at {w}px')
    pg.set_viewport_size({'width': 1440, 'height': 900})
    pg.click('.row >> nth=0'); pg.wait_for_timeout(450)
    pg.emulate_media(media='print'); pg.evaluate('window.dispatchEvent(new Event("beforeprint"))'); pg.wait_for_timeout(100)
    hidden = pg.evaluate("() => ['.index','.contents','.page-toolbar','.editor-body','.vrule','.grain'].filter(s => { const e = document.querySelector(s); return e && getComputedStyle(e).display !== 'none'; })")
    rec(not hidden and pg.inner_text('#print-title') != '', 'Print: only the open page is shown', json.dumps(hidden))
    pc = pg.evaluate("() => [getComputedStyle(document.getElementById('print-body')).color, getComputedStyle(document.getElementById('print-title')).color]")
    rec(pc[0] == 'rgb(59, 42, 30)', 'Print text is dark ink even while the dark theme is active', json.dumps(pc))
    rec('amended 7 Nov 2026' in pg.inner_text('#print-meta'), 'Print meta keeps the month capitalised', pg.inner_text('#print-meta'))
    pg.pdf(path=str(OUT / 'app-print.pdf'), format='A4', print_background=True)
    pg.emulate_media(media='screen')
    pg.evaluate("document.documentElement.setAttribute('data-theme','dark')")
    over = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
    rec(over <= 0, 'No horizontal overflow at 1440', str(over))
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.wait_for_timeout(100)
    rec(pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth") <= 0, 'No horizontal overflow at 390 (editor view)')
    pg.click('#back'); pg.wait_for_timeout(100)
    rec(pg.is_visible('#new-note') and pg.is_hidden('#page'), 'Mobile: Back returns to the contents, New entry visible')
    rec(not errs, 'No console errors or CSP violations', json.dumps(errs)[:200])
    ctx2 = b.new_context(viewport={'width': 1440, 'height': 900}); p2 = ctx2.new_page(); failed = []
    p2.on('response', lambda r: failed.append((r.status, r.url)) if r.status >= 400 else None)
    p2.goto(URL)
    p2.evaluate("d => localStorage.setItem('notetaker-notes', JSON.stringify({version:1, notes:d}))", SEED); p2.reload()
    rec(p2.locator('.row').count() == 5, 'Saved entries load after a reload')
    p2.fill('#search', 'two'); rec(p2.locator('.row').count() == 1, 'Search finds the matching entry'); p2.fill('#search', '')
    p2.click('.row >> nth=1'); p2.fill('#title', 'Edited title'); p2.wait_for_timeout(900)
    rec(p2.evaluate("JSON.parse(localStorage.getItem('notetaker-notes')).notes.some(n => n.title === 'Edited title')"), 'Saving writes the edited entry to localStorage')
    p2.reload(); p2.wait_for_timeout(200)
    titles = p2.eval_on_selector_all('.row-title', 'els => els.map(e => e.textContent)')
    rec('Edited title' in titles and len(titles) == 5, 'Edits persist after a page refresh', json.dumps(titles, ensure_ascii=False))
    rec(not failed, 'Every request (HTML, CSS, fonts, favicon, scripts) returns a success status', json.dumps(failed))
    ctx2.close()
    b.close()
for s, n, d in res: print(f'{s:5} {n}' + (f'  [{d}]' if d else ''))
print(sum(r[0]=='pass' for r in res), 'passed', sum(r[0]=='FAIL' for r in res), 'failed')
srv.shutdown()
